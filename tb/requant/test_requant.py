"""cocotb unit tests for rtl/requant.sv (SPEC v1.1 §1.2, §3.6, §6 row "Requant").

Expected values:
  * sw/crates/vec `unit requant` JSON (152 named directed cases + random, from
    splitsys_golden::requant), generated by the tb Makefile into $VEC_DIR;
  * tb/oracle (`requant` = splitsys_golden::requant) for the extra pipelining tests.
  * int32 bypass: out == acc (identity).
Port contract (requant.sv header): params load one lane per cycle and take effect
for data entering in the NEXT cycle; params are captured per beat; latency is
port to port, must equal splitsys_pkg::L_RQ - 1 (D-016).
"""

from __future__ import annotations

import json
import os

import cocotb

from splitsys_tb import (FallingEdge, RisingEdge, check, oracle, pkg_const, reset, scaled,
                         seed_rng, start_clock, uval)

LANES = 16


def vec_path() -> str:
    d = os.environ.get("VEC_DIR")
    if not d:
        raise AssertionError("VEC_DIR not set (run through `make -C tb requant`)")
    return os.path.join(d, "unit", "requant.json")


def s32(v: int) -> int:
    v &= 0xFFFFFFFF
    return v - (1 << 32) if v & 0x80000000 else v


async def setup(dut):
    dut.prm_we.value = 0
    dut.prm_lane.value = 0
    dut.prm_word.value = 0
    dut.bypass.value = 0
    dut.in_vld.value = 0
    dut.in_acc.value = 0
    await start_clock(dut)
    await reset(dut)


def prm_word(mult: int, shift: int) -> int:
    return (shift & 0xFF) << 16 | (mult & 0xFFFF)   # SPEC §1.3 RQPARAM {8'h0, shift, mult}


async def run(dut, cycles):
    """cycles: list of dict(prm=(lane, mult, shift)|None, beat=(bypass, accs[16])|None).
    Returns list of (cycle, out lanes signed) for every out_vld cycle."""
    outs = []
    for c, cyc in enumerate(cycles):
        await RisingEdge(dut.clk)
        p = cyc.get("prm")
        if p:
            dut.prm_we.value = 1
            dut.prm_lane.value = p[0]
            dut.prm_word.value = prm_word(p[1], p[2])
        else:
            dut.prm_we.value = 0
        b = cyc.get("beat")
        if b:
            dut.in_vld.value = 1
            dut.bypass.value = b[0]
            dut.in_acc.value = sum((a & 0xFFFFFFFF) << (32 * j) for j, a in enumerate(b[1]))
        else:
            dut.in_vld.value = 0
            dut.bypass.value = 0
            dut.in_acc.value = 0
        await FallingEdge(dut.clk)
        if uval(dut.out_vld):
            v = uval(dut.out_data)
            outs.append((c, [s32(v >> (32 * j)) for j in range(LANES)]))
    return outs


def check_beats(cycles, outs, expected, label, lat=None):
    """expected[i] = list of 16 expected signed values (or None) for beat i, in order."""
    beat_cycles = [c for c, cyc in enumerate(cycles) if cyc.get("beat")]
    check(len(outs) == len(beat_cycles), f"[{label}] out_vld count", expected=len(beat_cycles),
          got=len(outs))
    lats = {oc - bc for (oc, _), bc in zip(outs, beat_cycles)}
    check(len(lats) == 1, f"[{label}] latency not constant", latencies=sorted(lats))
    if lat is not None:
        check(lats == {lat}, f"[{label}] latency", expected=lat, got=sorted(lats))
    for i, ((oc, got), exp) in enumerate(zip(outs, expected)):
        for j in range(LANES):
            if exp[j] is None:
                continue
            b = cycles[beat_cycles[i]]["beat"]
            check(got[j] == exp[j], f"[{label}] lane value", beat=i, lane=j, cycle_in=beat_cycles[i],
                  acc=b[1][j], bypass=b[0], params=cycles[beat_cycles[i]].get("params_used", ["?"] * 16)[j],
                  expected=exp[j], got=got[j])
    return lats.pop() if lats else None


def schedule_cases(cases, rng, bypass_every=0):
    """Pack cases 16 per beat. Lane params for beat b are loaded in the 16 cycles before
    the beat; the beat itself shares its cycle with the first param write of beat b+1,
    which must NOT affect it (params take effect the next cycle)."""
    cycles = []
    expected = []
    groups = [cases[i:i + LANES] for i in range(0, len(cases), LANES)]
    for gi, g in enumerate(groups):
        g = g + [g[-1]] * (LANES - len(g))          # pad the last beat (expected repeated)
        for j, cs in enumerate(g):
            cycles.append({"prm": (j, cs["mult"], cs["shift"])})
        bank = [(cs["mult"], cs["shift"]) for cs in g]
        # the beat goes on the next cycle; the next group's lane-0 write is in the same cycle
        beat = {"beat": (0, [cs["acc"] for cs in g]), "params_used": bank}
        nxt = groups[gi + 1][0] if gi + 1 < len(groups) else None
        if nxt is not None:
            beat["prm"] = (0, nxt["mult"], nxt["shift"])   # must not affect this beat
        cycles.append(beat)
        expected.append([cs["y"] for cs in g])
        if bypass_every and gi % bypass_every == 0:
            accs = [rng.randint(-2**31, 2**31 - 1) for _ in range(LANES)]
            cycles.append({"beat": (1, accs)})
            expected.append(list(accs))
    cycles += [{}] * 16          # drain the pipeline
    return cycles, expected


@cocotb.test()
async def test_latency_equals_L_RQ(dut):
    """One beat in, out_vld exactly L_RQ - 1 cycles later (both int8 and bypass).
    D-016: L_RQ is sequencer-level (1 registered array drain-read mux + requant
    stages); the standalone requant.sv latency is defined as L_RQ - 1."""
    await setup(dut)
    lat = pkg_const("L_RQ") - 1   # D-016
    cycles = [{"prm": (j, 1, 1)} for j in range(LANES)] + [{}] * 3 + \
             [{"beat": (0, [2 * j + 1 for j in range(LANES)])}] + [{}] * 12 + \
             [{"beat": (1, [-j for j in range(LANES)])}] + [{}] * 12
    outs = await run(dut, cycles)
    beat_cycles = [c for c, cyc in enumerate(cycles) if cyc.get("beat")]
    measured = sorted({oc - bc for (oc, _), bc in zip(outs, beat_cycles)})
    dut._log.info(f"measured requant latency {measured}, splitsys_pkg::L_RQ - 1 = {lat} (D-016)")
    check(len(outs) == 2, "out_vld count", got=len(outs))
    check(measured == [lat], "requant latency != splitsys_pkg::L_RQ - 1 (D-016)", measured=measured, L_RQ_minus_1=lat)


@cocotb.test()
async def test_vec_requant_cases(dut):
    """Every case of sw/crates/vec unit/requant.json (named directed + random), bit-exact.
    Directed: shift 1 and 31, ties (±, every shift), ± saturation edges, mult 1 / 32767,
    product bit 47, int32 extremes. Bypass beats interleaved (identity)."""
    await setup(dut)
    with open(vec_path()) as f:
        vec = json.load(f)
    meta = vec["meta"]
    dut._log.info(f"vectors: {vec_path()} seed={meta['seed']} git={meta['git_hash']} "
                  f"dirty={meta['git_dirty']} n={len(vec['cases'])} n_directed={vec['n_directed']}")
    cases = vec["cases"]
    n = min(len(cases), vec["n_directed"] + scaled(100000))
    cases = cases[:n]
    rng = seed_rng(dut, "test_vec_requant_cases")
    ties = sum(1 for c in cases if c["tie"])
    sats = sum(1 for c in cases if c["sat"])
    cycles, expected = schedule_cases(cases, rng, bypass_every=7)
    # Cycle accounting: lane-0 writes of group b+1 happen in group b's beat cycle and
    # again at the start of group b+1 (harmless rewrite of the same value).
    outs = await run(dut, cycles)
    lat = check_beats(cycles, outs, expected, "vec")
    dut._log.info(f"{len(cases)} cases ({ties} ties, {sats} saturating), {len(expected)} beats, "
                  f"latency {lat}: all bit-exact")


@cocotb.test()
async def test_param_takes_effect_next_cycle(dut):
    """A param write in the same cycle as a beat must not affect that beat; a write in the
    cycle right after the beat must not affect it either (params captured per beat)."""
    await setup(dut)
    accs = [1000 + 37 * j for j in range(LANES)]
    cycles = [{"prm": (j, 3, 2)} for j in range(LANES)]
    cycles += [{"beat": (0, accs), "prm": (5, 32767, 31)}]       # same-cycle write to lane 5
    cycles += [{"prm": (6, 32767, 31)}]                          # next-cycle write to lane 6
    cycles += [{"beat": (0, accs)}] + [{}] * 12                 # this beat sees lanes 5, 6 new
    outs = await run(dut, cycles)
    reqs = [f"requant {a} 3 2" for a in accs]
    reqs += [f"requant {a} {32767 if j in (5, 6) else 3} {31 if j in (5, 6) else 2}"
             for j, a in enumerate(accs)]
    ys = [int(r.split()[0]) for r in oracle(reqs)]
    check_beats(cycles, outs, [ys[:16], ys[16:]], "param timing")


@cocotb.test()
async def test_back_to_back_beats_random(dut):
    """Fixed random params, a beat every cycle (fully pipelined), random int8/bypass mix,
    full-range and small accumulators; oracle = splitsys_golden::requant."""
    await setup(dut)
    rng = seed_rng(dut, "test_back_to_back_beats_random")
    for rnd in range(max(1, scaled(8))):
        params = [(rng.randint(1, 32767), rng.randint(1, 31)) for _ in range(LANES)]
        cycles = [{"prm": (j, m, s)} for j, (m, s) in enumerate(params)]
        beats = []
        for _ in range(256):
            byp = 1 if rng.random() < 0.15 else 0
            accs = [rng.randint(-2**31, 2**31 - 1) if rng.random() < 0.5 else rng.randint(-5000000, 5000000)
                    for _ in range(LANES)]
            beats.append((byp, accs))
            gap = rng.random() < 0.2
            cycles.append({"beat": (byp, accs)})
            if gap:
                cycles.append({})
        cycles += [{}] * 12
        reqs = [f"requant {a} {params[j][0]} {params[j][1]}" for (_, accs) in beats
                for j, a in enumerate(accs)]
        ys = [int(r.split()[0]) for r in oracle(reqs)]
        expected = []
        for i, (byp, accs) in enumerate(beats):
            expected.append(list(accs) if byp else ys[16 * i:16 * i + 16])
        outs = await run(dut, cycles)
        check_beats(cycles, outs, expected, f"b2b round {rnd}")
